"""Attach readable results and reproduction inputs to the imported evidence."""
import hashlib
from html.parser import HTMLParser
import json
from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parents[3]


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def imported(kind, source):
    relative = source.relative_to(REPO).as_posix()
    matches = [path.parent for path in (REPO / 'results' / kind).glob('*/run.json')
               if json.loads(path.read_text(encoding='utf-8')).get('experiment_path') == relative]
    if len(matches) != 1:
        raise ValueError((relative, matches))
    return matches[0]


report_source = ROOT / 'report-final'
destination = imported('benchmarks', report_source)
test_destination = imported('tests', report_source / 'tests')
page = (report_source / 'report.html').read_text(encoding='utf-8')
page = page.replace('href="comparison.json"', 'href="raw/comparison.json"')
page = page.replace('href="tests/summary.json"',
                    f'href="../../tests/{test_destination.name}/raw/checks.json"')
(destination / 'report.html').write_text(page, encoding='utf-8')

reproduction = destination / 'reproduction'
reproduction.mkdir(exist_ok=True)
names = ['analyze_measurements.py', 'run_measurements.py', 'prepare_fixtures.py',
         'setup.py', 'prepare_targets.py', 'verify.py', 'verify_all.py', 'verify_linux.py',
         'build_allocations.py', 'package_sources.py', 'package_report.py', 'finalize_report.py',
         'fixtures.json', 'source-manifests.json', 'allocation-expectations.json',
         'patch-checks.json', 'experiment.json', 'reviewed-decisions.json']
for name in names:
    shutil.copyfile(ROOT / name, reproduction / name)
manifest = {
    'purpose': 'Compact reproduction inputs; independent candidate patches and common harness are in patches/.',
    'original_workspace': str(REPO),
    'original_run_root': str(ROOT),
    'layout': 'Scripts assume results/local/experiments/sender-micro-20261025 and the recorded Windows/WSL paths. Recreate baseline commit, apply common-harness.patch to each source snapshot, then only its candidate patch. Main production files remain unchanged. Every source and instrumented configuration requires a separate Cargo target directory.',
    'fixture_reuse': 'manySmallFiles/bigFiles/mixed reuse the previous sender-20261025 fixtures. fixtures.json retains identities and generator provenance; wide-tree is generated by prepare_fixtures.py.',
    'execution': 'Build and verify first; run run_measurements.py all only after all compilers/tests stop. Never overlap timing commands. Existing measurements are not overwritten.',
    'files': {path.relative_to(destination).as_posix(): digest(path)
              for path in sorted(reproduction.iterdir()) if path.is_file()},
    'report_html_sha256': digest(destination / 'report.html'),
    'test_summary': (test_destination.relative_to(REPO) / 'raw/checks.json').as_posix(),
}
(destination / 'attachments.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')


class Links(HTMLParser):
    def __init__(self):
        super().__init__()
        self.links = []

    def handle_starttag(self, tag, attrs):
        if tag == 'a':
            self.links.extend(value for key, value in attrs if key == 'href')


parser = Links()
parser.feed(page)
for link in parser.links:
    assert (destination / link).is_file(), link
count = 0
for kind in ('benchmarks', 'tests'):
    for path in (REPO / 'results' / kind).glob('*/run.json'):
        run = json.loads(path.read_text(encoding='utf-8'))
        if not run.get('experiment_path', '').startswith(ROOT.relative_to(REPO).as_posix() + '/'):
            continue
        for evidence in run.get('evidence', []):
            if evidence.get('saved'):
                expected = evidence.get('extracted_sha256', evidence['sha256'])
                assert digest(path.parent / evidence['saved']) == expected, path
        count += 1
assert count == 47, count
print(destination / 'report.html')
print(f'Validated {len(parser.links)} HTML links and saved evidence hashes in {count} imported runs.')
